"""Trace validation of lean/OptimiKahan/MagmaFgmres.lean against the instrumented MAGMA 2.10.0 (trace.patch).

Input: trace_<n>.txt (stderr of the probe with MAGMA_TRACE=1), out_<n>.txt (probe stdout, one result line per call).
Two kinds of checks:
 (1) Replay: every call becomes one `#eval checkCall ...` line in TraceReplay.lean, which runs the model's own
     `fgmres` / `gmstrs` on the traced initial residual norm and the traced Givens estimates (exact rationals from the
     %a hex floats) and compares (niters, early_exit, iter, info) with what the library actually returned.  Equal
     `niters` means the model takes the same exit decision as the code at every step.
 (2) Assumptions of the model, checked on the trace in Python:
     A1 restrt = maxiter = solver_outer_itermax = min(n, 500)      (caller passes the same value twice)
     A2 x is set to 0 before FGMRES (X0_ZERO)                       (fgmres model starts from x = 0)
     A3 tol = gmtol = cte = fl(fl(Anrm*eps)*sqrt(n))                (the model's tol)
     A4 the code compares with the rounded eps1 = fl(tol*ro0); the model with the exact tol*ro0: no step decision differs
     A5 exactly one outer pass unless the early break fires        (theorem single_cycle)
     A6 the Givens estimate never increases: ro_0 <= ro0, ro_i <= ro_{i-1}, |s| <= 1  (theorem givens_nonincreasing,
        exact arithmetic; reported with the observed worst ratio)
     A7 FGMRES result is returned with no FALLBACK, iter = niters (theorem gmstrs_always_success)
Usage: python3 validate.py trace_512.txt trace_1024.txt trace_2048.txt   -> writes TraceReplay.lean, prints report
"""
import math
import sys
from fractions import Fraction as F


def hexf(tok):
    t = tok.strip()
    if t in ("nan", "-nan"):
        return math.nan
    if t in ("inf", "-inf"):
        return math.inf if t == "inf" else -math.inf
    return float.fromhex(t)


def kv(line):
    out = {}
    for part in line.split()[2:]:
        if "=" in part:
            k, v = part.split("=", 1)
            out[k] = v
    return out


def parse(path):
    calls, cur = [], None
    for line in open(path):
        if not line.startswith("MTRACE "):
            continue
        tag = line.split()[1]
        d = kv(line)
        if tag == "CTE":
            cur = {"cte": d, "events": [], "steps": [], "outer": 0}
            calls.append(cur)
        if cur is None:
            continue
        cur["events"].append(tag)
        if tag == "OUTER_START" and d.get("is_inner") == "0":
            cur["outer"] += 1
            cur.setdefault("ro0", hexf(d["ro"]))
        elif tag == "EARLY_BREAK":
            cur["early"] = True
        elif tag == "EPS1":
            cur["eps1"] = d
        elif tag == "STEP":
            cur["steps"].append(d)
        elif tag == "RETURN":
            cur["ret"] = d
        elif tag == "GMSTRS_RETURN":
            cur["gm"] = d
        elif tag == "FALLBACK":
            cur["fallback"] = d
        elif tag == "DLAG2S_OVERFLOW":
            cur["dlag2s"] = d
    return calls


def lean_val(x):
    if isinstance(x, float) and math.isnan(x):
        return "nan"
    if isinstance(x, float) and math.isinf(x):
        return "inf"
    q = F(x)
    return f"{q.numerator}:{q.denominator}"


def main(paths):
    lean = ["import MagmaFgmres", "open MagmaFgmres", "",
            "/-! Generated by experiments/magma_fgmres/trace/validate.py: replays traced MAGMA runs through the model. -/",
            "", "def parseV (s : String) : V :=",
            "  match s.splitOn \":\" with",
            "  | [a, b] => match a.toInt?, b.toNat? with",
            "    | some n, some d => .num ((n : Rat) / (d : Rat))",
            "    | _, _ => .nan",
            "  | _ => .nan  -- \"nan\"", "",
            "def parseQ (s : String) : Rat := match parseV s with | .num q => q | .nan => 0", "",
            "def checkCall (name : String) (maxiter : Nat) (tol ro0 : String) (ros : String) (tIters : Nat) (tEarly : Bool)",
            "    (tIter tInfo : Int) : String :=",
            "  let l := (ros.splitOn \",\").filter (· ≠ \"\") |>.map parseV",
            "  let f := fun i => l.getD i .nan",
            "  let r := fgmres maxiter (parseQ tol) (parseV ro0) f",
            "  let g := gmstrs maxiter (parseQ tol) (parseV ro0) f",
            "  if r.1 = tIters ∧ r.2 = tEarly ∧ g.1 = tIter ∧ g.2 = tInfo then s!\"OK       {name}\"",
            "  else s!\"MISMATCH {name}: model ({r.1}, {r.2}, {g.1}, {g.2}) vs trace ({tIters}, {tEarly}, {tIter}, {tInfo})\"", ""]
    fails = {f"A{i}": [] for i in range(1, 8)}
    unmodelled, ncalls, worst_ratio, worst_s = [], 0, 0.0, 0.0
    for path in paths:
        tag = path.replace("trace_", "n=").replace(".txt", "")
        for ci, c in enumerate(parse(path)):
            ncalls += 1
            name = f"{tag} call {ci + 1:2d}"
            cte = c["cte"]
            n = int(cte["n"])
            itermax = int(cte["solver_outer_itermax"])
            tol = hexf(cte["gmtol"])
            if "dlag2s" in c:
                unmodelled.append(f"{name}: dlag2s overflow -> fallback (outside the GMSTRS model)")
                continue
            # A1
            e1 = c.get("eps1")
            if itermax != min(n, 500) or (e1 and (int(e1["maxiter"]) != itermax or int(e1["restrt"]) != itermax)):
                fails["A1"].append(name)
            # A2
            if "X0_ZERO" not in c["events"]:
                fails["A2"].append(name)
            # A3
            anrm, eps = hexf(cte["Anrm"]), hexf(cte["eps"])
            if not (hexf(cte["cte"]) == tol == (anrm * eps) * math.sqrt(n)):
                fails["A3"].append(name)
            ro0 = c.get("ro0", math.nan)
            ros = [hexf(s["ro"]) for s in c["steps"]]
            early = bool(c.get("early"))
            # A4: decisions with rounded eps1 (code) vs exact tol*ro0 (model)
            if e1 and not math.isnan(ro0):
                eps1_r = hexf(e1["eps1"])
                exact = F(tol) * F(ro0)
                for r in ros:
                    if math.isnan(r) or math.isinf(r):
                        continue
                    if (F(r) <= F(eps1_r)) != (F(r) <= exact):
                        fails["A4"].append(name)
                        break
            # A5
            if (not early and c["outer"] != 1) or (early and c["outer"] != 1):
                fails["A5"].append(f"{name} (outer passes {c['outer']})")
            # A6
            prev = ro0
            for s, r in zip(c["steps"], ros):
                sv = hexf(s["s"])
                if not (math.isnan(r) or math.isnan(prev) or math.isinf(r)):
                    if prev > 0:
                        worst_ratio = max(worst_ratio, r / prev)
                    if r > prev:
                        fails["A6"].append(f"{name} ratio {r / prev:.17g}")
                        break
                if not math.isnan(sv):
                    worst_s = max(worst_s, abs(sv))
                prev = r
            # A7
            gm = c.get("gm")
            if "fallback" in c or gm is None or int(gm["iter"]) != int(c["ret"]["niters"]) or int(gm["info"]) != 0:
                fails["A7"].append(name)
            if any(math.isinf(x) for x in ros + [ro0]):
                unmodelled.append(f"{name}: Inf in traced values (the model has no Inf)")
            niters = int(c["ret"]["niters"])
            iter_ret, info_ret = int(gm["iter"]), int(gm["info"])
            lean.append(f'#eval checkCall "{name}" {itermax} "{lean_val(tol)}" "{lean_val(ro0)}" '
                        f'"{",".join(lean_val(r) for r in ros)}" {niters} {"true" if early else "false"} '
                        f'({iter_ret}) ({info_ret})')
    open("TraceReplay.lean", "w").write("\n".join(lean) + "\n")
    print(f"{ncalls} traced calls; TraceReplay.lean written")
    for k, v in fails.items():
        print(f"  assumption {k}: {'holds on all calls' if not v else f'FAILS on {len(v)}: ' + '; '.join(v[:5])}")
    print(f"  A6 detail: worst ro_i/ro_(i-1) = {worst_ratio:.17g}, worst |s| = {worst_s:.17g}")
    for u in unmodelled:
        print("  unmodelled:", u)


if __name__ == "__main__":
    main(sys.argv[1:])
